#!/usr/bin/env node
import { readFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';

const PHASES = new Set(['selftest', 'review', 'deploy', 'rollback']);
const phase = process.argv[2];
const taskPath = process.argv[3];
const approval = process.argv[4] ?? '';

function stop(code, detail = {}) {
  process.stdout.write(JSON.stringify({ status: code, ...detail }, null, 2) + '\n');
  process.exit(code === 'REVIEW_READY' || code === 'LIVE_VERIFIED' || code === 'ROLLBACK_VERIFIED' || code === 'SELFTEST_PASS' ? 0 : 2);
}

function fail(message, detail = {}) {
  stop('EXECUTION_FAILED', { message, ...detail });
}

if (!PHASES.has(phase) || !taskPath) {
  fail('Usage: node kryo-baseline-change.mjs <selftest|review|deploy|rollback> <task.json> [approval-token]');
}

const task = JSON.parse(await readFile(taskPath, 'utf8'));

function md5(text) {
  return createHash('md5').update(text, 'utf8').digest('hex');
}

function deepEqual(a, b) {
  return JSON.stringify(a) === JSON.stringify(b);
}

function getPath(obj, path) {
  return path.split('.').reduce((cur, key) => cur?.[key], obj);
}

function setPath(obj, path, value) {
  const keys = path.split('.');
  let cur = obj;
  for (let i = 0; i < keys.length - 1; i += 1) {
    if (!cur || typeof cur !== 'object' || !(keys[i] in cur)) throw new Error(`Missing path segment ${keys.slice(0, i + 1).join('.')}`);
    cur = cur[keys[i]];
  }
  const leaf = keys.at(-1);
  if (!cur || typeof cur !== 'object' || !(leaf in cur)) throw new Error(`Missing path ${path}`);
  cur[leaf] = value;
}

function splitTemplate(raw) {
  const commentMatch = raw.match(/^\s*\/\*[\s\S]*?\*\/\s*/);
  const prefix = commentMatch?.[0] ?? raw.slice(0, Math.max(0, raw.indexOf('{')));
  const jsonText = raw.slice(prefix.length).trim();
  if (!jsonText.startsWith('{')) throw new Error('Theme template JSON body not found after optional autogenerated comment');
  return { prefix, value: JSON.parse(jsonText) };
}

function serializeTemplate(prefix, value) {
  return `${prefix}${JSON.stringify(value, null, 2)}`;
}

function assertEq(label, observed, expected, drift) {
  if (!deepEqual(observed, expected)) drift.push({ field: label, expected, observed });
}

function assertContains(label, observed, expected, drift) {
  if (typeof observed !== 'string' || !observed.includes(expected)) drift.push({ field: label, expected_contains: expected, observed });
}

function verifyProduct(product, drift) {
  const exp = task.product.expected;
  assertEq('product.id', String(product.id), String(exp.id), drift);
  assertEq('product.handle', product.handle, exp.handle, drift);
  assertEq('product.status', String(product.status).toUpperCase(), String(exp.status).toUpperCase(), drift);
  assertEq('product.template_suffix', product.template_suffix, exp.template_suffix, drift);
  assertEq('product.total_inventory', product.total_inventory, exp.total_inventory, drift);
  assertEq('product.variant_count', product.variants?.length ?? 0, exp.variant_count, drift);
  const variant = product.variants?.[0];
  assertEq('variant.id', String(variant?.id), String(exp.variant_id), drift);
  assertEq('variant.inventory_quantity', variant?.inventory_quantity, exp.variant_inventory_quantity, drift);
  assertEq('variant.sellable_now', variant?.sellable_now, true, drift);
}

function verifyMedia(mediaPayload, expectedIds, drift, label = 'product.media_ids') {
  const ids = (mediaPayload.media ?? []).map((m) => m.id);
  assertEq(label, ids, expectedIds, drift);
}

function verifyTemplateSentinels(parsed, sentinels, drift, prefix = 'template') {
  for (const s of sentinels) {
    const observed = getPath(parsed, s.path);
    if ('equals' in s) assertEq(`${prefix}.${s.path}`, observed, s.equals, drift);
    if ('contains' in s) assertContains(`${prefix}.${s.path}`, observed, s.contains, drift);
  }
}

function applyOperations(source) {
  const target = structuredClone(source);
  for (const op of task.operations) {
    if (op.op === 'set') {
      const observed = getPath(target, op.path);
      if (!deepEqual(observed, op.from)) throw new Error(`Operation precondition failed at ${op.path}: expected ${JSON.stringify(op.from)}, observed ${JSON.stringify(observed)}`);
      setPath(target, op.path, op.to);
      continue;
    }
    if (op.op === 'insert_block_after') {
      const section = getPath(target, `sections.${op.section}`);
      if (!section?.blocks || !Array.isArray(section.block_order)) throw new Error(`Insert target section invalid: ${op.section}`);
      if (section.blocks[op.block_id]) throw new Error(`Block already exists: ${op.block_id}`);
      const afterIndex = section.block_order.indexOf(op.after_id);
      if (afterIndex < 0) throw new Error(`after_id not found: ${op.after_id}`);
      if (section.block_order[afterIndex + 1] !== op.before_id) throw new Error(`Insert adjacency drift after ${op.after_id}`);
      section.blocks[op.block_id] = structuredClone(op.block);
      section.block_order.splice(afterIndex + 1, 0, op.block_id);
      continue;
    }
    throw new Error(`Unsupported operation ${op.op}`);
  }
  return target;
}

function verifyExpectedChanges(source, target) {
  const expected = applyOperations(source);
  if (!deepEqual(expected, target)) throw new Error('Review template contains semantic changes outside the frozen operations');
  const section = getPath(target, `sections.${task.constraints.block_section}`);
  if ((section?.block_order?.length ?? 0) > task.constraints.max_blocks_per_section) throw new Error('Review template exceeds frozen block-count guard');
}

async function loadDotEnv() {
  for (const file of ['.env.local', '.env.production.local']) {
    if (!existsSync(file)) continue;
    const text = await readFile(file, 'utf8');
    for (const rawLine of text.split(/\r?\n/)) {
      const line = rawLine.trim();
      if (!line || line.startsWith('#')) continue;
      const i = line.indexOf('=');
      if (i < 1) continue;
      const key = line.slice(0, i).trim();
      let value = line.slice(i + 1).trim();
      if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) value = value.slice(1, -1);
      if (!(key in process.env)) process.env[key] = value;
    }
  }
}

async function ensureEnvironment() {
  await loadDotEnv();
  if (process.env.MARKETING_SYNC_SECRET) return;
  if (process.env.KRYO_ENV_BOOTSTRAPPED === '1') stop('ENVIRONMENT_UNAVAILABLE', { reason: 'MARKETING_SYNC_SECRET unavailable after Vercel production env bootstrap' });
  const args = ['env', 'run', '-e', 'production', '--', process.execPath, process.argv[1], phase, taskPath];
  if (approval) args.push(approval);
  const env = {
    ...process.env,
    KRYO_ENV_BOOTSTRAPPED: '1',
    VERCEL_ORG_ID: task.vercel.team_id,
    VERCEL_PROJECT_ID: task.vercel.project_id,
  };
  const run = spawnSync('vercel', args, { stdio: 'inherit', env });
  if (run.error?.code === 'ENOENT') stop('ENVIRONMENT_UNAVAILABLE', { reason: 'Vercel CLI not installed and MARKETING_SYNC_SECRET not present' });
  process.exit(run.status ?? 2);
}

class ExecutionError extends Error {
  constructor(code, detail) {
    super(`${code}: ${JSON.stringify(detail)}`);
    this.code = code;
    this.detail = detail;
  }
}

async function api(path, options = {}) {
  const url = path.startsWith('http') ? path : `${task.execution.base_url}${path}`;
  const headers = { 'x-sync-secret': process.env.MARKETING_SYNC_SECRET, ...(options.headers ?? {}) };
  let body;
  if (options.body !== undefined) {
    headers['content-type'] = 'application/json';
    body = JSON.stringify(options.body);
  }
  const res = await fetch(url, { method: options.method ?? 'GET', headers, body, redirect: 'follow', cache: 'no-store' });
  const text = await res.text();
  let payload;
  try { payload = JSON.parse(text); } catch { payload = { raw: text.slice(0, 1000) }; }
  if (!res.ok) {
    const code = res.status === 409 && payload?.error === 'PRECONDITION_DRIFT' ? 'PRECONDITION_DRIFT' : 'EXECUTION_SURFACE_UNAVAILABLE';
    throw new ExecutionError(code, { route: path, http_status: res.status, response: payload });
  }
  return payload;
}

async function publicHtml(url) {
  const sep = url.includes('?') ? '&' : '?';
  const res = await fetch(`${url}${sep}kryo_review_nonce=${Date.now()}`, { redirect: 'follow', cache: 'no-store', headers: { 'cache-control': 'no-cache' } });
  if (!res.ok) throw new Error(`Public storefront fetch failed ${res.status} for ${url}`);
  return await res.text();
}

function themeAssetPath(key) {
  return `${task.execution.routes.theme_asset}?theme_id=${task.theme.id}&key=${encodeURIComponent(key)}`;
}

async function readState() {
  const [product, media, liveAsset, dependency] = await Promise.all([
    api(`${task.execution.routes.product}?handle=${encodeURIComponent(task.product.expected.handle)}`),
    api(`${task.execution.routes.media}?product_id=${encodeURIComponent(task.product.gid)}`),
    api(themeAssetPath(task.theme.live_key)),
    api(themeAssetPath(task.dependencies.testimonial_block.key)),
  ]);
  return { product, media, liveAsset, dependency };
}

function preflightState(state) {
  const drift = [];
  verifyProduct(state.product, drift);
  verifyMedia(state.media, task.media.expected_before_ids, drift);
  assertEq('live_template.key', state.liveAsset.key, task.theme.live_key, drift);
  assertEq('live_template.md5', md5(state.liveAsset.value ?? ''), task.theme.live_md5, drift);
  assertEq('testimonial_dependency.md5', md5(state.dependency.value ?? ''), task.dependencies.testimonial_block.md5, drift);
  const { value: parsed } = splitTemplate(state.liveAsset.value ?? '');
  verifyTemplateSentinels(parsed, task.source_sentinels, drift, 'live');
  verifyTemplateSentinels(parsed, task.protected_sentinels, drift, 'protected');
  if (drift.length) stop('PRECONDITION_DRIFT', { mismatches: drift });
  return parsed;
}

async function writeTheme(key, value) {
  return api(task.execution.routes.deploy_asset, { method: 'POST', body: { theme_id: task.theme.id, key, value } });
}

async function buildReview() {
  const state = await readState();
  const source = preflightState(state);
  const review = applyOperations(source);
  verifyExpectedChanges(source, review);
  const { prefix } = splitTemplate(state.liveAsset.value);
  const reviewRaw = serializeTemplate(prefix, review);
  if (Buffer.byteLength(reviewRaw, 'utf8') > task.constraints.max_template_bytes) throw new Error('Review template exceeds Shopify JSON-template byte guard');

  await writeTheme(task.theme.review_key, reviewRaw);
  const [reviewAsset, liveAfter, productAfter, mediaAfter] = await Promise.all([
    api(themeAssetPath(task.theme.review_key)),
    api(themeAssetPath(task.theme.live_key)),
    api(`${task.execution.routes.product}?handle=${encodeURIComponent(task.product.expected.handle)}`),
    api(`${task.execution.routes.media}?product_id=${encodeURIComponent(task.product.gid)}`),
  ]);
  const reviewParsed = splitTemplate(reviewAsset.value ?? '').value;
  verifyExpectedChanges(source, reviewParsed);
  const verification = [];
  assertEq('live_template_after_review.md5', md5(liveAfter.value ?? ''), task.theme.live_md5, verification);
  verifyProduct(productAfter, verification);
  verifyMedia(mediaAfter, task.media.expected_before_ids, verification, 'media_after_review');
  verifyTemplateSentinels(reviewParsed, task.review_sentinels, verification, 'review');
  verifyTemplateSentinels(reviewParsed, task.protected_sentinels, verification, 'review_protected');
  if (verification.length) stop('REVIEW_VERIFY_FAILED', { mismatches: verification });

  const [preview, liveHtml] = await Promise.all([publicHtml(task.preview.url), publicHtml(task.preview.live_url)]);
  const publicErrors = [];
  for (const marker of task.preview.review_contains) if (!preview.includes(marker)) publicErrors.push({ surface: 'review', missing: marker });
  for (const marker of task.preview.review_not_contains) if (preview.includes(marker)) publicErrors.push({ surface: 'review', forbidden_present: marker });
  for (const marker of task.preview.live_contains_before_review) if (!liveHtml.includes(marker)) publicErrors.push({ surface: 'live', missing_expected_old_marker: marker });
  for (const marker of task.preview.live_not_contains_before_review) if (liveHtml.includes(marker)) publicErrors.push({ surface: 'live', unexpected_new_marker: marker });
  if (publicErrors.length) stop('STOREFRONT_VERIFY_FAILED', { mismatches: publicErrors });

  stop('REVIEW_READY', {
    task_id: task.task_id,
    preview_url: task.preview.url,
    review_template: task.theme.review_key,
    live_source_unchanged: true,
    product_unchanged: true,
    product_media_unchanged: true,
    operations: task.operations.map((o) => o.label),
    planned_media: task.media.review_packet,
  });
}

async function deployApproved() {
  if (approval !== task.approval_token) stop('APPROVAL_REQUIRED', { expected_token: task.approval_token });
  const state = await readState();
  const source = preflightState(state);
  const reviewAsset = await api(themeAssetPath(task.theme.review_key));
  const reviewParsed = splitTemplate(reviewAsset.value ?? '').value;
  verifyExpectedChanges(source, reviewParsed);
  const { prefix } = splitTemplate(state.liveAsset.value);
  const expectedReviewRaw = serializeTemplate(prefix, applyOperations(source));
  if (!deepEqual(reviewParsed, splitTemplate(expectedReviewRaw).value)) stop('REVIEW_DRIFT', { reason: 'Review artifact no longer matches frozen task' });

  await writeTheme(task.theme.rollback_key, state.liveAsset.value);
  const rollbackAsset = await api(themeAssetPath(task.theme.rollback_key));
  if (md5(rollbackAsset.value ?? '') !== task.theme.live_md5) stop('ROLLBACK_SNAPSHOT_FAILED', { reason: 'Rollback template bytes do not match pre-deployment live template' });

  const startedAt = new Date().toISOString();
  let liveTemplateChanged = false;
  try {
    await writeTheme(task.theme.live_key, reviewAsset.value);
    liveTemplateChanged = true;
    const liveNew = await api(themeAssetPath(task.theme.live_key));
    const liveNewParsed = splitTemplate(liveNew.value ?? '').value;
    if (!deepEqual(liveNewParsed, reviewParsed)) throw new Error('Live template reread differs from approved review artifact');

    await api(task.execution.routes.media, {
      method: 'POST',
      body: {
        action: 'add_reorder',
        product_id: task.product.gid,
        expected_before_ids: task.media.expected_before_ids,
        file_ids: task.media.add_existing_file_ids,
        desired_order: task.media.desired_order,
      },
    });

    const [productAfter, mediaAfter, liveAfter] = await Promise.all([
      api(`${task.execution.routes.product}?handle=${encodeURIComponent(task.product.expected.handle)}`),
      api(`${task.execution.routes.media}?product_id=${encodeURIComponent(task.product.gid)}`),
      api(themeAssetPath(task.theme.live_key)),
    ]);
    const verify = [];
    const productExpected = { ...task.product.expected, total_inventory: productAfter.total_inventory, variant_inventory_quantity: productAfter.variants?.[0]?.inventory_quantity };
    assertEq('product.handle', productAfter.handle, productExpected.handle, verify);
    assertEq('product.template_suffix', productAfter.template_suffix, productExpected.template_suffix, verify);
    assertEq('product.variant_id', String(productAfter.variants?.[0]?.id), String(productExpected.variant_id), verify);
    verifyMedia(mediaAfter, task.media.desired_order, verify, 'media_after_deploy');
    const liveParsed = splitTemplate(liveAfter.value ?? '').value;
    verifyTemplateSentinels(liveParsed, task.review_sentinels, verify, 'live_after_deploy');
    verifyTemplateSentinels(liveParsed, task.protected_sentinels, verify, 'live_protected');
    if (verify.length) throw new Error(`Post-deploy verification failed: ${JSON.stringify(verify)}`);

    const liveHtml = await publicHtml(task.preview.live_url);
    const storefrontErrors = [];
    for (const marker of task.preview.review_contains) if (!liveHtml.includes(marker)) storefrontErrors.push({ missing: marker });
    for (const marker of task.preview.review_not_contains) if (liveHtml.includes(marker)) storefrontErrors.push({ forbidden_present: marker });
    if (storefrontErrors.length) throw new Error(`Live storefront verification failed: ${JSON.stringify(storefrontErrors)}`);

    stop('LIVE_VERIFIED', {
      task_id: task.task_id,
      deployed_at_utc: startedAt,
      live_template: task.theme.live_key,
      rollback_template: task.theme.rollback_key,
      media_order: task.media.desired_order,
      monitoring: task.monitoring,
    });
  } catch (error) {
    const rollbackErrors = [];
    if (liveTemplateChanged) {
      try { await writeTheme(task.theme.live_key, state.liveAsset.value); }
      catch (e) { rollbackErrors.push(`template: ${String(e?.message ?? e)}`); }
    }
    try {
      const mediaNow = await api(`${task.execution.routes.media}?product_id=${encodeURIComponent(task.product.gid)}`);
      const idsNow = (mediaNow.media ?? []).map((m) => m.id);
      if (deepEqual(idsNow, task.media.desired_order)) {
        await api(task.execution.routes.media, {
          method: 'POST',
          body: {
            action: 'remove_restore',
            product_id: task.product.gid,
            expected_before_ids: task.media.desired_order,
            file_ids: task.media.add_existing_file_ids,
            desired_order: task.media.expected_before_ids,
          },
        });
      }
    } catch (e) { rollbackErrors.push(`media: ${String(e?.message ?? e)}`); }
    if (rollbackErrors.length) stop('ROLLBACK_FAILED', { cause: String(error?.message ?? error), rollback_errors: rollbackErrors });
    stop('DEPLOY_FAILED_ROLLED_BACK', { cause: String(error?.message ?? error) });
  }
}

async function rollbackRelease() {
  if (approval !== task.rollback_token) stop('APPROVAL_REQUIRED', { expected_token: task.rollback_token });
  const [live, rollbackAsset, media] = await Promise.all([
    api(themeAssetPath(task.theme.live_key)),
    api(themeAssetPath(task.theme.rollback_key)),
    api(`${task.execution.routes.media}?product_id=${encodeURIComponent(task.product.gid)}`),
  ]);
  const rollbackParsed = splitTemplate(rollbackAsset.value ?? '').value;
  const liveParsed = splitTemplate(live.value ?? '').value;
  const desiredLive = splitTemplate((await api(themeAssetPath(task.theme.review_key))).value ?? '').value;
  if (!deepEqual(liveParsed, desiredLive)) stop('PRECONDITION_DRIFT', { reason: 'Live template no longer equals approved Control v2 review artifact; manual research required before rollback' });
  const idsNow = (media.media ?? []).map((m) => m.id);
  if (!deepEqual(idsNow, task.media.desired_order)) stop('PRECONDITION_DRIFT', { reason: 'Live media no longer equals deployed Control v2 media order; manual research required before rollback', observed: idsNow });

  await writeTheme(task.theme.live_key, rollbackAsset.value);
  await api(task.execution.routes.media, {
    method: 'POST',
    body: {
      action: 'remove_restore',
      product_id: task.product.gid,
      expected_before_ids: task.media.desired_order,
      file_ids: task.media.add_existing_file_ids,
      desired_order: task.media.expected_before_ids,
    },
  });
  const [liveAfter, mediaAfter] = await Promise.all([
    api(themeAssetPath(task.theme.live_key)),
    api(`${task.execution.routes.media}?product_id=${encodeURIComponent(task.product.gid)}`),
  ]);
  const mismatches = [];
  assertEq('rollback.live_md5', md5(liveAfter.value ?? ''), task.theme.live_md5, mismatches);
  verifyMedia(mediaAfter, task.media.expected_before_ids, mismatches, 'rollback.media_ids');
  verifyTemplateSentinels(rollbackParsed, task.source_sentinels, mismatches, 'rollback_template');
  if (mismatches.length) stop('ROLLBACK_VERIFY_FAILED', { mismatches });
  stop('ROLLBACK_VERIFIED', { task_id: task.task_id, rolled_back_at_utc: new Date().toISOString() });
}

function selftest() {
  const sample = `/* auto */\n{\n  "sections": {\n    "x": {\n      "blocks": {\n        "a": {"settings":{"value":"old"}},\n        "b": {"settings":{}}\n      },\n      "block_order": ["a","b"]\n    }\n  }\n}`;
  const parsed = splitTemplate(sample);
  if (parsed.prefix !== '/* auto */\n') throw new Error('prefix preservation selftest failed');
  const oldOps = task.operations;
  task.operations = [
    { op: 'set', path: 'sections.x.blocks.a.settings.value', from: 'old', to: 'new' },
    { op: 'insert_block_after', section: 'x', after_id: 'a', before_id: 'b', block_id: 'c', block: { settings: { ok: true } } },
  ];
  try {
    const changed = applyOperations(parsed.value);
    if (getPath(changed, 'sections.x.blocks.a.settings.value') !== 'new') throw new Error('set operation selftest failed');
    if (changed.sections.x.block_order.join(',') !== 'a,c,b') throw new Error('insert operation selftest failed');
    const roundtrip = splitTemplate(serializeTemplate(parsed.prefix, changed));
    if (!deepEqual(roundtrip.value, changed)) throw new Error('roundtrip selftest failed');
  } finally {
    task.operations = oldOps;
  }
  stop('SELFTEST_PASS', { task_id: task.task_id });
}

try {
  if (phase === 'selftest') selftest();
  await ensureEnvironment();
  if (phase === 'review') await buildReview();
  if (phase === 'deploy') await deployApproved();
  if (phase === 'rollback') await rollbackRelease();
} catch (error) {
  if (error instanceof ExecutionError) stop(error.code, error.detail);
  fail(String(error?.stack ?? error));
}
